    @Test
    public void testEncode() {
        // Set up the converter to match Pascal
        PascalTextConverter converter = new PascalTextConverter();
        converter.setSpaceEncodingThreshold(0);
        // We need to make the expected text be in 1024-byte chunks
        final byte[] expected = Arrays.copyOf(ENCODED_TEXT, 1024);

        assertArrayEquals(expected, converter.toData(PASCAL_TEXT).asBytes());
    }

    @Test
    public void testDecode() {
        PascalTextConverter converter = new PascalTextConverter();
        assertEquals(PASCAL_TEXT, converter.toText(DataBuffer.wrap(ENCODED_TEXT)));
    }
