package org.applecommander.converter;

import java.util.Arrays;

/// A generic word processor converter. It separates text from control sequences.
public interface WordProcessorConverter {
    /// Convert the document using the given event handler callback.
    void convert(EventHandler handler);

    /// The event handler is the callback mechanism for rendering the document.
    interface EventHandler {
        /// Add a text string into the resulting document.
        void text(String text);

        /// Handler a control element. Note that some elements _can_ have parameters, but
        /// they can vary across formats, so supply sensible defaults and code for the no-args
        /// situations.
        void control(Control control, int... args);

        /// Identifies which section of the document is being processed.
        void section(DocumentSection documentSection);

        /// Indicate what type of font to use. It is likely that the font does not exist
        /// on the system, so leaving that to implementation to "figure it out."
        void font(FontFamily fontFamily);
    }

    /// A simple class that allows "snooping" into the events generated by any
    /// `WordProcessorConverter`.
    class Snoop implements EventHandler {
        private final EventHandler eventHandler;

        public Snoop(EventHandler eventHandler) {
            this.eventHandler = eventHandler;
        }

        /// Add a text string into the resulting document.
        @Override
        public void text(String text) {
            System.out.printf("WP TEXT: '%s'\n", text);
            this.eventHandler.text(text);
        }

        /// Handler a control element. Note that some elements _can_ have parameters, but
        /// they can vary across formats, so supply sensible defaults and code for the no-args
        /// situations.
        @Override
        public void control(WordProcessorConverter.Control control, int... args) {
            System.out.printf("WP CONTROL: %s %s\n", control, Arrays.stream(args).mapToObj(Integer::toString).toList());
            this.eventHandler.control(control, args);
        }

        /// Identifies which section of the document is being processed.
        @Override
        public void section(DocumentSection documentSection) {
            System.out.printf("WP SECTION: %s\n", documentSection);
            this.eventHandler.section(documentSection);
        }

        /// Indicate what type of font to use. It is likely that the font does not exist
        /// on the system, so leaving that to implementation to "figure it out."
        public void font(FontFamily fontFamily) {
            System.out.printf("WP FONT FAMILY: %s\n", fontFamily);
            this.eventHandler.font(fontFamily);
        }
    }

    /// Identifies the document section to be processed.
    enum DocumentSection {
        BODY, HEADER, FOOTER;
    }

    /// Control elements that the word processing document may generate. Not all features are
    /// present, and they will likely grow as more documents are handled.
    enum Control {
        BEGIN_BOLD,
        END_BOLD,
        BEGIN_SUPERSCRIPT,
        END_SUPERSCRIPT,
        BEGIN_SUBSCRIPT,
        END_SUBSCRIPT,
        BEGIN_UNDERLINE,
        END_UNDERLINE,
        SET_PAGE_NUMBER,
        SHOW_PAGE_NUMBER,
        PRINT_DATE,
        PRINT_TIME,
        INDENT_CHARS,
        ALIGN_JUSTIFY,
        ALIGN_LEFT,
        ALIGN_RIGHT,
        ALIGN_CENTER,
        SPACING_SINGLE,
        SPACING_DOUBLE,
        SPACING_TRIPLE,
        PAGE_BREAK,
        BEGIN_ITALIC,
        END_ITALIC,
        FONT_SIZE,
    }

    /// Identifies the Font Family by ID.
    /// Taken from Apple IIGS Technical Note #41.
    ///
    /// Notes:
    /// * Shaston was the default system UI font.
    /// * Monaco was the default fixed-width font.
    /// * The default monospace and proportional fonts are *not* system fonts,
    ///   but are included so tools can pick an "I don't care" type font (or if
    ///   fonts don't apply, but general type of font can be identified).
    enum FontFamily {
        CHICAGO(0xfffd, false),
        SHASTON(0xfffe, false),
        NEW_YORK(2, false),
        GENEVA(3, false),
        MONACO(4, true),
        VENICE(5, false),
        LONDON(6, false),
        ATHENS(7, false),
        SAN_FRANCISCO(8, false),
        TORONTO(9, false),
        CAIRO(11, false),
        LOS_ANGELES(12, false),
        DEFAULT_MONOSPACE(0x8000, true),
        DEFAULT_PROPORTIONAL(0x8001, false);

        public final int id;
        public final boolean fixedWidth;

        FontFamily(int id, boolean fixedWidth) {
            this.id = id;
            this.fixedWidth = fixedWidth;
        }
    }
}
